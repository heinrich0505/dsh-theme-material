/**
 * 把 src/*.mjs 内联成外壳能吃的 client.js。
 *
 * 外壳的模块加载器要的是 `window.__ModuleLoader__.load({ id, factory })`，
 * 不是 ES module，所以这里做一次极简内联：去掉 import/export 关键字，
 * 按依赖顺序拼进同一个 factory 作用域。产物要提交，外壳不负责构建。
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/** 依赖顺序：被依赖的在前。 */
const ORDER = ['tokens.mjs', 'color.mjs', 'skins.mjs', 'derive.mjs', 'row-css.mjs', 'settings-row.mjs', 'runtime.mjs']

/**
 * 去掉 import 语句与行首 export 关键字。
 * 所有 import 都写成单行，这里也只处理单行与续行两种形态。
 * @param {string} source
 * @returns {string}
 */
function strip(source) {
  const kept = []
  let inImport = false
  for (const line of source.split('\n')) {
    if (inImport) {
      if (/from\s+['"][^'"]+['"]\s*$/.test(line)) inImport = false
      continue
    }
    if (/^\s*import\s/.test(line)) {
      if (!/from\s+['"][^'"]+['"]\s*$/.test(line)) inImport = true
      continue
    }
    kept.push(line)
  }
  const body = kept.join('\n').replace(/^export\s+/gm, '')
  if (/^\s*(import|export)\s/m.test(body)) {
    throw new Error('strip: 还残留 import/export 语句')
  }
  return body.trimEnd()
}

const sections = []
for (const file of ORDER) {
  const source = await readFile(join(root, 'src', file), 'utf8')
  sections.push(`    /* ---- src/${file} ---- */\n${strip(source)}\n`)
}

const banner = `/* dsh-theme-material — generated by scripts/build.mjs. Do not edit by hand. */`

const output = `${banner}
window.__ModuleLoader__.load({
  id: 'dsh-theme-material',
  factory(require) {
    'use strict'

${sections.join('\n')}
    const core = {
      skins: SKINS,
      getSkin,
      deriveSkin,
      defaultSkin: DEFAULT_SKIN,
      // 外壳的模块加载器给的 require：用来拿 react 与 jsx runtime 写设置行组件。
      moduleRequire: typeof require === 'function' ? require : undefined,
      createSettingsRow,
    }
    return {
      name: 'themeMaterial',
      inject: [],
      apply(ctx) {
        applyMaterial(ctx, core)
      },
    }
  },
})
`

await writeFile(join(root, 'client.js'), output, 'utf8')
console.log(`client.js 已生成：${output.length} 字节，${output.split('\n').length} 行`)
